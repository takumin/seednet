//! Keeping cloud-init from rendering the network, by its runtime config.

use std::fs;
use std::io::ErrorKind;
use std::path::Path;

use anyhow::{Context, Result};
use yaml_serde::Value;

/// The runtime config of cloud-init, which ds-identify writes when the rootfs starts and cloud-init
/// merges over /etc/cloud. The initrd cannot write it, since ds-identify rewrites it.
const RUNTIME_CONFIG: &str = "run/cloud-init/cloud.cfg";

/// Sets `network: {config: disabled}` in the runtime config of the rootfs.
pub fn take_over(sysroot: &Path) -> Result<()> {
    disable_network(&sysroot.join(RUNTIME_CONFIG))
}

/// Sets `network: {config: disabled}` in the runtime config, keeping the rest of it.
fn disable_network(path: &Path) -> Result<()> {
    const DISABLED: &str = "network: {config: disabled}\n";

    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(error) if error.kind() == ErrorKind::NotFound => String::new(),
        Err(error) => {
            return Err(error).with_context(|| format!("failed to read {}", path.display()));
        }
    };
    let mut config: Value = if text.trim().is_empty() {
        Value::Mapping(Default::default())
    } else {
        yaml_serde::from_str(&text)
            .with_context(|| format!("invalid YAML in {}", path.display()))?
    };
    let Value::Mapping(mapping) = &mut config else {
        anyhow::bail!("{} is not a mapping", path.display());
    };

    let new_text = match mapping.get("network") {
        Some(network) if network.get("config").and_then(Value::as_str) == Some("disabled") => {
            return Ok(());
        }
        // Appending keeps the file as ds-identify wrote it, comments and all.
        None => {
            let separator = if text.is_empty() || text.ends_with('\n') {
                ""
            } else {
                "\n"
            };
            format!("{text}{separator}# Added by seednet, which renders the network.\n{DISABLED}")
        }
        Some(_) => {
            mapping.insert(
                Value::String("network".into()),
                yaml_serde::from_str("{config: disabled}")?,
            );
            yaml_serde::to_string(&config)?
        }
    };

    let dir = path.parent().context("a file without a directory")?;
    fs::create_dir_all(dir).with_context(|| format!("failed to create {}", dir.display()))?;
    fs::write(path, new_text).with_context(|| format!("failed to write {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn disables_the_network_and_keeps_the_rest() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("cloud.cfg");

        // As ds-identify writes it.
        fs::write(&path, "# generated by ds-identify\ndatasource_list: [ NoCloud, None ]\n")
            .unwrap();
        disable_network(&path).unwrap();
        let text = fs::read_to_string(&path).unwrap();
        assert!(
            text.starts_with("# generated by ds-identify\ndatasource_list: [ NoCloud, None ]\n")
        );
        let config: Value = yaml_serde::from_str(&text).unwrap();
        assert_eq!(config["network"]["config"].as_str(), Some("disabled"));

        // Done twice, it changes nothing.
        disable_network(&path).unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), text);

        // A network config of its own is replaced.
        fs::write(&path, "datasource_list: [NoCloud]\nnetwork: {version: 2}\n").unwrap();
        disable_network(&path).unwrap();
        let config: Value = yaml_serde::from_str(&fs::read_to_string(&path).unwrap()).unwrap();
        assert_eq!(config["network"]["config"].as_str(), Some("disabled"));
        assert_eq!(config["datasource_list"][0].as_str(), Some("NoCloud"));

        // No file yet.
        let path = dir.path().join("missing/cloud.cfg");
        disable_network(&path).unwrap();
        assert_eq!(
            fs::read_to_string(&path).unwrap(),
            "# Added by seednet, which renders the network.\nnetwork: {config: disabled}\n"
        );
    }
}
