//! The interfaces that both versions of network-config convert to, before they are rendered for
//! systemd-networkd or NetworkManager.

use std::net::IpAddr;

use anyhow::{Context, Result, bail};

use crate::ip::Cidr;
use crate::params::BridgeParams;

/// The first line of every file seednet writes, by which it tells its own files from the others.
pub const HEADER: &str = "# Generated by seednet from the NoCloud network-config.\n";

/// The values of `macaddress` that netplan passes to NetworkManager for it to make the address, and
/// that networkd has no setting for.
pub const MAC_POLICIES: &[&str] = &["permanent", "random", "stable", "preserve"];

/// One interface: a physical one, or one that the config creates.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Network {
    /// The ID in network-config, which names a created interface and the files.
    pub id: String,
    pub kind: Kind,

    /// What finds a physical interface. A created one goes by its ID.
    pub mac_address: Option<String>,
    pub name: Option<String>,
    /// Globs of the driver, any of which matches.
    pub drivers: Vec<String>,
    /// The name to rename a physical interface to.
    pub set_name: Option<String>,
    /// The MAC address to give the interface, or one of the policies of NetworkManager in
    /// [`MAC_POLICIES`].
    pub set_mac_address: Option<String>,

    pub mtu: Option<u32>,
    pub optional: bool,

    /// The ID of the bond or bridge this is a port of, which then has no addresses of its own.
    pub controller: Option<String>,
    /// As a bridge port, its path cost and priority.
    pub port_cost: Option<u32>,
    pub port_priority: Option<u32>,

    pub dhcp4: bool,
    pub dhcp6: bool,
    /// The DHCP overrides, one for both DHCPv4 and DHCPv6 as netplan takes them with networkd.
    pub dhcp_overrides: DhcpOverrides,
    /// `mac` or `duid`: what DHCPv4 tells the server it is.
    pub dhcp_identifier: Option<String>,
    pub accept_ra: Option<bool>,
    pub link_local: Option<String>,
    pub ipv6_privacy: Option<bool>,
    pub ipv6_mtu: Option<u32>,

    pub addresses: Vec<Cidr>,
    /// The options of some of `addresses`.
    pub address_options: Vec<AddressOptions>,
    pub gateways: Vec<IpAddr>,
    pub nameservers: Vec<IpAddr>,
    pub search: Vec<String>,
    pub routes: Vec<Route>,
    pub routing_policy: Vec<RoutingRule>,
}

/// What DHCP may set, and how, where the defaults do not do. They mean what they do in netplan with
/// networkd, which writes them to the `[DHCP]` section: `route-metric` is also the metric of the
/// routes of the router advertisements, `use-dns`, `use-ntp`, `use-domains` and `send-hostname` are
/// for DHCPv6 too, and the others are for DHCPv4 alone.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct DhcpOverrides {
    pub use_dns: Option<bool>,
    pub use_ntp: Option<bool>,
    pub use_hostname: Option<bool>,
    pub use_mtu: Option<bool>,
    pub use_routes: Option<bool>,
    /// `yes`, `no` or `route`, as networkd takes it.
    pub use_domains: Option<String>,
    pub send_hostname: Option<bool>,
    pub hostname: Option<String>,
    pub route_metric: Option<u32>,
}

impl DhcpOverrides {
    /// The metric of the routes of DHCP that netplan writes when the config says none, which is
    /// the one of NetworkManager for Ethernet.
    pub const DEFAULT_ROUTE_METRIC: u32 = 100;

    pub fn is_empty(&self) -> bool {
        *self == Self::default()
    }
}

/// The options of one address.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AddressOptions {
    pub address: Cidr,
    pub label: Option<String>,
    /// `forever` or `0`, which makes the address deprecated for new connections.
    pub preferred_lifetime: Option<String>,
}

/// One routing policy rule.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct RoutingRule {
    pub from: Option<Cidr>,
    pub to: Option<Cidr>,
    pub table: Option<u32>,
    pub priority: Option<u32>,
    pub mark: Option<u32>,
    pub type_of_service: Option<u8>,
}

impl RoutingRule {
    pub fn is_ipv6(&self) -> bool {
        self.from
            .or(self.to)
            .is_some_and(|cidr| cidr.addr.is_ipv6())
    }
}

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub enum Kind {
    #[default]
    Ethernet,
    Bond(Bond),
    Bridge(Bridge),
    Vlan {
        id: u16,
        /// The ID of the interface it is on.
        link: String,
    },
}

/// The bond parameters, with the values that both networkd and the kernel take. Times are in
/// milliseconds.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Bond {
    pub mode: Option<String>,
    pub lacp_rate: Option<String>,
    pub mii_monitor_interval: Option<u32>,
    pub up_delay: Option<u32>,
    pub down_delay: Option<u32>,
    pub transmit_hash_policy: Option<String>,
    pub ad_select: Option<String>,
    pub arp_interval: Option<u32>,
    pub arp_ip_targets: Vec<IpAddr>,
    pub fail_over_mac_policy: Option<String>,
    pub min_links: Option<u32>,
    /// The ID of the preferred port.
    pub primary: Option<String>,
}

/// The bridge parameters. Times are in seconds.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Bridge {
    pub stp: Option<bool>,
    pub forward_delay: Option<u32>,
    pub hello_time: Option<u32>,
    pub max_age: Option<u32>,
    pub ageing_time: Option<u32>,
    pub priority: Option<u32>,
}

/// One route.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Route {
    /// `0.0.0.0/0` or `::/0` for a default route, which tells its family as netplan writes it.
    pub destination: Cidr,
    pub gateway: Option<IpAddr>,
    pub metric: Option<u32>,
    pub on_link: bool,
    pub table: Option<u32>,
}

impl Route {
    /// The default route via `gateway`.
    pub fn default_via(gateway: IpAddr) -> Self {
        Self {
            destination: Cidr::default_route(gateway.is_ipv6()),
            gateway: Some(gateway),
            metric: None,
            on_link: false,
            table: None,
        }
    }
}

impl Network {
    /// Whether the interface gets any address from this config, so that name servers apply to it.
    pub fn is_configured(&self) -> bool {
        self.dhcp4 || self.dhcp6 || self.accept_ra == Some(true) || !self.addresses.is_empty()
    }

    /// Whether the config creates this interface, rather than finding it.
    pub fn is_virtual(&self) -> bool {
        !matches!(self.kind, Kind::Ethernet)
    }

    /// The name the interface ends up with, when the config says it: a created one is named by its
    /// ID, and a physical one by `set-name` or by a name without wildcards.
    pub fn ifname(&self) -> Option<&str> {
        if self.is_virtual() {
            return Some(&self.id);
        }
        self.set_name.as_deref().or(self
            .name
            .as_deref()
            .filter(|name| !name.contains(['*', '?', '['])))
    }

    /// The ID with only the characters that are safe in a file name.
    pub fn file_id(&self) -> String {
        self.id
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
                    c
                } else {
                    '_'
                }
            })
            .collect()
    }
}

/// Makes `ports` the ports of the bond or bridge `controller`, with the settings of a bridge.
pub fn attach_ports(
    networks: &mut [Network],
    controller: &str,
    ports: &[String],
    bridge: Option<&BridgeParams>,
) -> Result<()> {
    for port in ports {
        if port == controller {
            bail!("{controller} is a port of itself");
        }
        let Some(network) = networks.iter_mut().find(|network| network.id == *port) else {
            bail!("{controller} has the port {port}, which the config does not have");
        };
        if let Some(other) = &network.controller {
            bail!("{port} is a port of both {other} and {controller}");
        }
        network.controller = Some(controller.to_owned());
        if let Some(bridge) = bridge {
            network.port_cost = bridge.path_costs.get(port).copied();
            network.port_priority = bridge.port_priorities.get(port).copied();
        }
    }

    if let Some(bridge) = bridge {
        for port in bridge
            .path_costs
            .keys()
            .chain(bridge.port_priorities.keys())
        {
            if !ports.contains(port) {
                bail!("{controller} has a setting for {port}, which is not its port");
            }
        }
    }

    Ok(())
}

/// Checks what refers to another interface, once all of them are known.
pub fn check_references(networks: &[Network]) -> Result<()> {
    for network in networks {
        match &network.kind {
            Kind::Vlan { link, .. } => {
                if !networks.iter().any(|other| other.id == *link) {
                    bail!("the VLAN {} is on {link}, which the config does not have", network.id);
                }
                if *link == network.id {
                    bail!("the VLAN {} is on itself", network.id);
                }
            }
            Kind::Bond(bond) => {
                if let Some(primary) = &bond.primary {
                    let is_port = networks.iter().any(|other| {
                        other.id == *primary && other.controller.as_deref() == Some(&network.id)
                    });
                    if !is_port {
                        bail!("the primary {primary} of {} is not its port", network.id);
                    }
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// Checks a name that the kernel must give an interface: at most 15 bytes, with no `/`, `:` or
/// white space, and neither `.` nor `..`.
pub fn check_ifname(name: &str) -> Result<()> {
    if name.is_empty() || name.len() > 15 {
        bail!("{name:?} is not 1 to 15 bytes");
    }
    if name == "."
        || name == ".."
        || name.contains(['/', ':'])
        || name.contains(char::is_whitespace)
    {
        bail!("{name:?} has a character that an interface name cannot");
    }
    Ok(())
}

/// Checks a MAC address: six octets, or twenty for InfiniBand, as netplan takes it.
pub fn check_mac(mac: &str) -> Result<()> {
    let octets: Vec<_> = mac.split(':').collect();
    if !matches!(octets.len(), 6 | 20)
        || !octets
            .iter()
            .all(|octet| octet.len() == 2 && octet.bytes().all(|b| b.is_ascii_hexdigit()))
    {
        bail!("{mac:?} is not a MAC address");
    }
    Ok(())
}

/// Checks a value that goes in a file as one word, such as a name, a glob or a domain: one that a
/// line break, a space or a separator would split, or that would start another key.
pub fn check_word(what: &str, value: &str) -> Result<()> {
    if value.is_empty() {
        bail!("{what} is empty");
    }
    if value
        .chars()
        .any(|c| c.is_control() || c.is_whitespace() || matches!(c, ';' | ',' | '\\' | '"' | '\''))
    {
        bail!("{what} {value:?} has a character that it cannot");
    }
    Ok(())
}

impl Network {
    /// Checks the values that go in the files as they are.
    pub fn check_values(&self) -> Result<()> {
        let id = &self.id;
        check_word("the ID", id)?;
        for (what, value) in [
            ("the name", &self.name),
            ("the set-name", &self.set_name),
            ("the DHCP hostname", &self.dhcp_overrides.hostname),
        ] {
            if let Some(value) = value {
                check_word(&format!("{what} of {id}"), value)?;
            }
        }
        for driver in &self.drivers {
            check_word(&format!("the driver of {id}"), driver)?;
        }
        for search in &self.search {
            check_word(&format!("the search domain of {id}"), search)?;
        }
        for options in &self.address_options {
            if let Some(label) = &options.label {
                check_word(&format!("the label of {}", options.address), label)?;
            }
        }
        if let Some(mac) = &self.mac_address {
            check_mac(mac).with_context(|| format!("invalid match of {id}"))?;
        }
        if let Some(mac) = &self.set_mac_address
            && !MAC_POLICIES.contains(&mac.as_str())
        {
            check_mac(mac).with_context(|| format!("invalid macaddress of {id}"))?;
        }
        Ok(())
    }
}

/// Adds a value to a list unless it is already there.
pub fn push_unique<T: PartialEq>(list: &mut Vec<T>, value: T) {
    if !list.contains(&value) {
        list.push(value);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitizes_the_file_id() {
        let network = Network {
            id: "en*/x".into(),
            ..Default::default()
        };
        assert_eq!(network.file_id(), "en__x");
    }

    #[test]
    fn knows_the_interface_name_when_the_config_says_it() {
        let named = |name: &str, set_name: Option<&str>| Network {
            name: Some(name.into()),
            set_name: set_name.map(Into::into),
            ..Default::default()
        };
        assert_eq!(named("eth0", None).ifname(), Some("eth0"));
        assert_eq!(named("en*", None).ifname(), None);
        assert_eq!(named("en*", Some("lan")).ifname(), Some("lan"));
        let bond = Network {
            id: "bond0".into(),
            kind: Kind::Bond(Bond::default()),
            ..Default::default()
        };
        assert_eq!(bond.ifname(), Some("bond0"));
    }
}
