#[test]
fn bad_references_fail() {
    for config in [
        // A port that is not there.
        "version: 2\nbonds: {bond0: {interfaces: [eth9]}}\n",
        // A port of two controllers.
        "version: 2\nethernets: {eth0: {}}\n\
        bonds: {bond0: {interfaces: [eth0]}, bond1: {interfaces: [eth0]}}\n",
        // A VLAN on nothing, or out of range.
        "version: 2\nvlans: {v: {id: 10, link: eth9}}\n",
        "version: 2\nethernets: {eth0: {}}\nvlans: {v: {id: 4095, link: eth0}}\n",
        // A primary that is not a port.
        "version: 2\nethernets: {eth0: {}}\nbonds: {bond0: {parameters: {primary: eth0}}}\n",
        // set-name without match, and an ID twice.
        "version: 2\nethernets: {eth0: {set-name: x}}\n",
        "version: 2\nethernets: {br0: {}}\nbridges: {br0: {}}\n",
        // Two IDs that make the same file name.
        "version: 2\nethernets: {\"a/b\": {}, a_b: {}}\n",
    ] {
        assert!(convert(config).is_err(), "{config}");
    }
}

#[test]
fn file_names_stay_when_the_config_changes() {
    let names = |text: &str| -> Vec<String> {
        files(text, Backend::Networkd)
            .into_iter()
            .map(|(name, _)| name)
            .filter(|name| name.contains("eth1"))
            .collect()
    };
    // eth0 comes before eth1, or not at all: either way, eth1 has the same files, so that a
    // drop-in or an override in /etc still applies to them.
    assert_eq!(
        names("version: 2\nethernets: {eth1: {dhcp4: true}}\n"),
        names("version: 2\nethernets: {eth0: {dhcp4: true}, eth1: {dhcp4: true}}\n")
    );
}
