#[test]
fn v1_reads_as_cloud_init_converts_it_for_netplan() {
    let config = include_str!("fixtures/v1-cloud-init-conversion.yaml");
    let conversion = convert(config).unwrap();
    assert_eq!(
        conversion.warnings,
        [
            "skipping dns_nameservers of a dhcp subnet of eth0, which only a static one takes",
            "skipping the mtu of eth0, since its IPv4 subnet has another",
        ]
    );
    let files = render(config);

    // ipv6_slaac is dhcp6, the metric of the DHCP subnets is their route metric, and the gateway
    // out of the subnet is on the link.
    assert_eq!(files[0].0, "10-seednet-eth0.network");
    assert_eq!(
        files[0].1,
        format!(
            "{HEADER}
[Match]
Name=eth0

[Link]
MTUBytes=9000
RequiredForOnline=no

[Network]
DHCP=yes
IPv6MTUBytes=1400
Address=198.51.100.10/24
Address=2001:db8::10/64
DNS=203.0.113.53
DNS=192.0.2.54
Domains=global.example

[DHCPv4]
ClientIdentifier=mac
RouteMetric=200
UseMTU=yes

[IPv6AcceptRA]
RouteMetric=200

[Route]
Destination=0.0.0.0/0
Gateway=192.0.2.1
GatewayOnLink=yes
Metric=50

[Route]
Destination=10.0.0.0/8
Gateway=198.51.100.254
Metric=50

[Route]
Destination=10.1.0.0/16
Gateway=198.51.100.254
Metric=10
"
        )
    );

    // The name servers of every interface go to those with static addresses and none of their
    // own, which the dhcp subnet of eth0 does not give it, and the one of eth0 is added to them.
    let dns = |network: &seednet::Network| {
        let nameservers: Vec<_> = network
            .nameservers
            .iter()
            .map(ToString::to_string)
            .collect();
        (nameservers, network.search.clone())
    };
    let networks = &conversion.networks;
    assert_eq!(networks.len(), 3);
    assert_eq!(
        dns(&networks[0]),
        (
            vec!["203.0.113.53".to_owned(), "192.0.2.54".to_owned()],
            vec!["global.example".to_owned()]
        )
    );
    assert_eq!(
        dns(&networks[1]),
        (vec!["203.0.113.53".to_owned()], vec!["global.example".to_owned()])
    );
    assert_eq!(dns(&networks[2]), (vec![], vec!["own.example".to_owned()]));

    // netplan takes no different metrics for DHCPv4 and DHCPv6.
    let different = include_str!("fixtures/v1-different-dhcp-metrics.yaml");
    assert!(convert(different).is_err());
}

#[test]
fn bond_values_and_interface_names_are_checked() {
    let bond = |parameters: &str| {
        convert(&format!(
            "version: 2\nethernets: {{eth0: {{}}}}\nbonds:\n  bond0:\n    interfaces: [eth0]\n    \
            parameters: {parameters}\n"
        ))
    };
    assert!(bond("{mode: 802.3ad, lacp-rate: fast, transmit-hash-policy: layer3+4}").is_ok());
    for invalid in [
        "{mode: 4}",
        "{mode: balance-tcp}",
        "{lacp-rate: 1}",
        "{transmit-hash-policy: layer4}",
        "{ad-select: fastest}",
        "{fail-over-mac-policy: always}",
    ] {
        assert!(bond(invalid).is_err(), "{invalid}");
    }

    assert!(convert("version: 2\nbonds: {bond-uplink-0123: {}}\n").is_err());
    assert!(
        convert("version: 2\nvlans: {vlan.10: {id: 10, link: eth0}}\nethernets: {eth0: {}}\n")
            .is_ok()
    );
    assert!(
        convert("version: 2\nethernets:\n  lan:\n    match: {name: en*}\n    set-name: a/b\n")
            .is_err()
    );
    // A name with wildcards is matched, not given.
    assert!(
        convert("version: 2\nethernets:\n  lan:\n    match: {name: enp0s31f6-very-long*}\n")
            .is_ok()
    );
}

