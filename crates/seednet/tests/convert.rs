use seednet::{Backend, Conversion, Dir, convert};

/// The files of `backend`, by name.
fn files(text: &str, backend: Backend) -> Vec<(String, String)> {
    let conversion = convert(text).unwrap();
    let mut warnings = Vec::new();
    seednet::render(&conversion.networks, backend, "10-seednet", &mut warnings)
        .into_iter()
        .map(|file| (file.name, file.content))
        .collect()
}

/// The `.network` files only.
fn render(text: &str) -> Vec<(String, String)> {
    files(text, Backend::Networkd)
        .into_iter()
        .filter(|(name, _)| name.ends_with(".network"))
        .collect()
}

