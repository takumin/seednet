#[test]
fn skipped_parts_are_returned_as_warnings() {
    let conversion = convert(
        "version: 2\nwifis: {wl0: {}}\nbonds:\n  bond0:\n    parameters: {mode: balance-rr, \
        gratuitous-arp: 1}\n",
    )
    .unwrap();
    assert_eq!(
        conversion.warnings,
        [
            "skipping the unsupported type: wifis",
            "skipping the unsupported bond parameter gratuitous-arp of bond0"
        ]
    );

    let v1_route_on_no_interface = "version: 1\nconfig:\n  - type: route\n    \
        destination: 198.51.100.0/24\n    gateway: 192.0.2.1\n";
    let conversion = convert(v1_route_on_no_interface).unwrap();
    assert!(conversion.networks.is_empty());
    assert_eq!(conversion.warnings, ["skipping a route via 192.0.2.1, on no interface"]);
}

